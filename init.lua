-- Keystroke Board: records every keypress system-wide into SQLite and shows a live
-- Keychron K3 v1 board in a borderless window on the portrait (Dell) monitor.

local M = {}

local MODULE_DIR = debug.getinfo(1, "S").source:match("^@(.*)/[^/]*$")  -- this project's folder
local HTML_PATH = MODULE_DIR .. "/board.html"
local DB_PATH = MODULE_DIR .. "/keys.db"  -- kept out of git by .gitignore in this folder
local HISTORY_DAYS = 7         -- raw press history kept this long; all-time counts are kept forever
local HISTORY_PAGE = 10        -- rows per page for key history on the board
local CLIP_PAGE = 5            -- rows per page for clipboard history on the board
local CLIP_PREVIEW = 400       -- characters of each clipboard item sent to the board
local CLIP_MAX_CHARS = 200000  -- longer clipboard text is truncated before saving
local CLIP_POLL = 0.5          -- seconds between clipboard checks

-- pasteboard markers apps use for secrets and throwaway data (nspasteboard.org); never recorded
local SKIP_PASTEBOARD_TYPES = {
  ["org.nspasteboard.ConcealedType"] = true,
  ["org.nspasteboard.TransientType"] = true,
  ["org.nspasteboard.AutoGeneratedType"] = true,
  ["com.agilebits.onepassword"] = true,
}
local TOGGLE_HOTKEY = { { "ctrl", "alt", "cmd" }, "k" }

local T = hs.eventtap.event.types
local AUTOREPEAT = hs.eventtap.event.properties.keyboardEventAutorepeat

-- macOS virtual keycode -> web KeyboardEvent.code (the board's layout uses web codes)
local CODES = {
  [0] = "KeyA", [1] = "KeyS", [2] = "KeyD", [3] = "KeyF", [4] = "KeyH", [5] = "KeyG", [6] = "KeyZ",
  [7] = "KeyX", [8] = "KeyC", [9] = "KeyV", [11] = "KeyB", [12] = "KeyQ", [13] = "KeyW", [14] = "KeyE",
  [15] = "KeyR", [16] = "KeyY", [17] = "KeyT", [18] = "Digit1", [19] = "Digit2", [20] = "Digit3",
  [21] = "Digit4", [22] = "Digit6", [23] = "Digit5", [24] = "Equal", [25] = "Digit9", [26] = "Digit7",
  [27] = "Minus", [28] = "Digit8", [29] = "Digit0", [30] = "BracketRight", [31] = "KeyO", [32] = "KeyU",
  [33] = "BracketLeft", [34] = "KeyI", [35] = "KeyP", [36] = "Enter", [37] = "KeyL", [38] = "KeyJ",
  [39] = "Quote", [40] = "KeyK", [41] = "Semicolon", [42] = "Backslash", [43] = "Comma", [44] = "Slash",
  [45] = "KeyN", [46] = "KeyM", [47] = "Period", [48] = "Tab", [49] = "Space", [50] = "Backquote",
  [51] = "Backspace", [53] = "Escape",
  [54] = "MetaRight", [55] = "MetaLeft", [56] = "ShiftLeft", [57] = "CapsLock", [58] = "AltLeft",
  [59] = "ControlLeft", [60] = "ShiftRight", [61] = "AltRight", [62] = "ControlRight",
  [122] = "F1", [120] = "F2", [99] = "F3", [118] = "F4", [96] = "F5", [97] = "F6", [98] = "F7",
  [100] = "F8", [101] = "F9", [109] = "F10", [103] = "F11", [111] = "F12", [105] = "PrintScreen",
  [115] = "Home", [116] = "PageUp", [117] = "Delete", [119] = "End", [121] = "PageDown",
  [123] = "ArrowLeft", [124] = "ArrowRight", [125] = "ArrowDown", [126] = "ArrowUp",
  [160] = "F3", [131] = "F4",  -- Mission Control / Launchpad, sent by the K3's F3/F4 in Mac mode
  [63] = "Fn",                 -- the physical fn key, as a flagsChanged event (see FN_TAPPED)
}

-- media keys the K3's F-row sends in Mac mode (arrive as system-defined events, not keyDown)
local MEDIA = {
  BRIGHTNESS_DOWN = "F1", BRIGHTNESS_UP = "F2",
  PREVIOUS = "F7", REWIND = "F7", PLAY = "F8", NEXT = "F9", FAST = "F9",
  MUTE = "F10", SOUND_DOWN = "F11", SOUND_UP = "F12",
}

local NAMES = {
  Backquote = "`", Minus = "-", Equal = "=", BracketLeft = "[", BracketRight = "]", Backslash = "\\",
  Semicolon = ";", Quote = "'", Comma = ",", Period = ".", Slash = "/", Space = "Space", Enter = "Return",
  Backspace = "Backspace", Tab = "Tab", Escape = "Esc", CapsLock = "Caps Lock",
  ArrowLeft = "←", ArrowRight = "→", ArrowUp = "↑", ArrowDown = "↓",
  Home = "Home", End = "End", PageUp = "Page Up", PageDown = "Page Down", Delete = "Del", PrintScreen = "PrtSc", Fn = "Fn",
  ShiftLeft = "Shift", ShiftRight = "Shift", ControlLeft = "Control", ControlRight = "Control",
  AltLeft = "Option", AltRight = "Option", MetaLeft = "Command", MetaRight = "Command",
}

-- macOS sends 179 as a down+up pair after a short fn tap (the Globe action), never while fn is held;
-- the real press is keycode 63, so 179 is ignored to avoid counting each tap twice
local FN_TAPPED = 179

local MOD_CLASS = {
  ShiftLeft = "shift", ShiftRight = "shift", ControlLeft = "ctrl", ControlRight = "ctrl",
  AltLeft = "alt", AltRight = "alt", MetaLeft = "cmd", MetaRight = "cmd",
}
local MOD_SYMBOL = { ctrl = "⌃", alt = "⌥", shift = "⇧", cmd = "⌘" }

local function keyName(code, keycode)
  if code then
    local single = code:match("^Key(%u)$") or code:match("^Digit(%d)$")
    return single or NAMES[code] or code
  end
  local mapped = hs.keycodes.map[keycode]
  return mapped and tostring(mapped):upper() or ("Key " .. keycode)
end

local function modPrefix(flags)
  local parts = {}
  for _, cls in ipairs({ "ctrl", "alt", "shift", "cmd" }) do  -- macOS order
    if flags[cls] then parts[#parts + 1] = MOD_SYMBOL[cls] end
  end
  return #parts > 0 and (table.concat(parts, "+") .. "+") or ""
end

-- storage ---------------------------------------------------------------------

local db, insertPress, bumpCount, insertClip
local buffer = {}
local lastClip  -- { kind, content } of the newest clipboard item, to skip repeats

local function openDb()
  db = hs.sqlite3.open(DB_PATH)
  db:exec([[
    PRAGMA journal_mode = WAL;
    CREATE TABLE IF NOT EXISTS presses (ts INTEGER NOT NULL, label TEXT NOT NULL);
    CREATE INDEX IF NOT EXISTS presses_ts ON presses (ts);
    CREATE TABLE IF NOT EXISTS counts (label TEXT PRIMARY KEY, n INTEGER NOT NULL);
    CREATE TABLE IF NOT EXISTS clips (id INTEGER PRIMARY KEY, ts INTEGER NOT NULL, kind TEXT NOT NULL, content TEXT NOT NULL, app TEXT);
    CREATE INDEX IF NOT EXISTS clips_ts ON clips (ts);
  ]])
  insertClip = db:prepare("INSERT INTO clips (ts, kind, content, app) VALUES (?, ?, ?, ?)")
  insertPress = db:prepare("INSERT INTO presses (ts, label) VALUES (?, ?)")
  bumpCount = db:prepare("INSERT INTO counts (label, n) VALUES (?, 1) ON CONFLICT (label) DO UPDATE SET n = n + 1")
end

local function nowMs() return math.floor(hs.timer.secondsSinceEpoch() * 1000) end

-- writes happen in batches on a timer so the event tap callback never waits on disk
local function flush()
  if #buffer == 0 then return end
  local pending = buffer
  buffer = {}
  db:exec("BEGIN")
  for _, p in ipairs(pending) do
    insertPress:bind_values(p.t, p.label); insertPress:step(); insertPress:reset()
    bumpCount:bind_values(p.label); bumpCount:step(); bumpCount:reset()
  end
  if db:exec("COMMIT") ~= hs.sqlite3.OK then print("keystroke_board: write failed: " .. db:errmsg()) end
end

local function prune()
  local cutoff = nowMs() - HISTORY_DAYS * 86400000
  db:exec("DELETE FROM presses WHERE ts < " .. cutoff .. "; DELETE FROM clips WHERE ts < " .. cutoff .. ";")
end

-- board window ----------------------------------------------------------------

local ready = false
local uiQueue, uiScheduled = {}, false

local function sendNow(msgs)
  if ready and M.wv then
    M.wv:evaluateJavaScript("window.KB && KB.batch(" .. hs.json.encode(msgs) .. ")")
  end
end

-- coalesce UI updates and send them outside the event tap callback
local function ui(msg)
  uiQueue[#uiQueue + 1] = msg
  if uiScheduled then return end
  uiScheduled = true
  hs.timer.doAfter(0, function()
    uiScheduled = false
    local q = uiQueue
    uiQueue = {}
    sendNow(q)
  end)
end

local function pageArgs(offset, limit)
  return math.max(0, math.floor(offset)), math.min(100, math.max(1, math.floor(limit)))
end

local function clipPage(offset, limit)
  offset, limit = pageArgs(offset, limit)
  local rows, total = {}, 0
  local sql = string.format(
    "SELECT id, ts, kind, substr(content, 1, %d), length(content), app FROM clips ORDER BY id DESC LIMIT %d OFFSET %d",
    CLIP_PREVIEW, limit, offset)
  for id, ts, kind, preview, len, app in db:urows(sql) do
    rows[#rows + 1] = { id = id, t = ts, kind = kind, preview = preview, length = len, app = app }
  end
  for n in db:urows("SELECT COUNT(*) FROM clips") do total = n end
  return { type = "clipsPage", offset = offset, total = total, rows = rows }
end

local function historyPage(offset, limit)
  flush()
  offset, limit = pageArgs(offset, limit)
  local rows, total = {}, 0
  for ts, label in db:urows(string.format("SELECT ts, label FROM presses ORDER BY ts DESC LIMIT %d OFFSET %d", limit, offset)) do
    rows[#rows + 1] = { t = ts, label = label }
  end
  for n in db:urows("SELECT COUNT(*) FROM presses") do total = n end
  return { type = "historyPage", offset = offset, total = total, rows = rows }
end

local function snapshot()
  flush()
  local counts = {}
  for label, n in db:urows("SELECT label, n FROM counts") do counts[#counts + 1] = { label, n } end
  local page = historyPage(0, HISTORY_PAGE)
  local clips = clipPage(0, CLIP_PAGE)
  return { type = "snapshot", counts = counts, history = page.rows, historyTotal = page.total,
           clips = clips.rows, clipsTotal = clips.total, dbPath = DB_PATH, historyDays = HISTORY_DAYS }
end

local currentStatus
local function setStatus(s, force)
  if s == currentStatus and not force then return end
  currentStatus = s
  ui({ type = "status", state = s })
end

local function clearAll()
  flush()
  db:exec("DELETE FROM presses; DELETE FROM counts; DELETE FROM clips;")
  lastClip = nil
  sendNow({ snapshot() })
end

-- clipboard -------------------------------------------------------------------

local lastChangeCount

local function utf8Cut(s, n)
  local cut = utf8.offset(s, n + 1)
  return cut and s:sub(1, cut - 1) or s
end

local function readClip()
  local has = {}
  for _, t in ipairs(hs.pasteboard.pasteboardTypes() or {}) do
    if SKIP_PASTEBOARD_TYPES[t] then return nil end
    has[t] = true
  end
  -- text only: copied files also carry their name as text, so skip those
  if has["public.file-url"] then return nil end
  local text = hs.pasteboard.readString()
  if not text or text == "" or not utf8.len(text) then return nil end
  return { kind = "text", content = text }
end

local function recordClip()
  local ok, c = pcall(readClip)
  if not ok then print("keystroke_board: clipboard read failed: " .. tostring(c)); return end
  if not c then return end
  if lastClip and lastClip.kind == c.kind and lastClip.content == c.content then return end
  lastClip = { kind = c.kind, content = c.content }
  if utf8.len(c.content) > CLIP_MAX_CHARS then c.content = utf8Cut(c.content, CLIP_MAX_CHARS) end
  local app = ""
  pcall(function() app = hs.application.frontmostApplication():name() end)
  local ts = nowMs()
  insertClip:bind_values(ts, c.kind, c.content, app); insertClip:step(); insertClip:reset()
  ui({ type = "clip", id = db:last_insert_rowid(), t = ts, kind = c.kind, app = app,
       preview = utf8Cut(c.content, CLIP_PREVIEW), length = utf8.len(c.content) })
end

local function pollClipboard()
  local cc = hs.pasteboard.changeCount()
  if cc == lastChangeCount then return end
  lastChangeCount = cc
  if not M.paused then recordClip() end
end

-- put a saved item back on the clipboard
local function copyClip(id)
  for content in db:urows("SELECT content FROM clips WHERE id = " .. math.floor(id)) do
    lastClip = { kind = "text", content = content }  -- so the poller doesn't save it again
    hs.pasteboard.setContents(content)
    ui({ type = "copied", id = id })
  end
end

local function targetScreen()
  local screens = hs.screen.allScreens()
  for _, s in ipairs(screens) do
    if (s:name() or ""):upper():find("DELL") then return s end
  end
  for _, s in ipairs(screens) do
    local f = s:frame()
    if f.h > f.w then return s end
  end
  return hs.screen.primaryScreen()
end

local function placeWindow()
  if M.wv then M.wv:frame(targetScreen():frame()) end
end

local function createWindow()
  local uc = hs.webview.usercontent.new("kb")
  uc:setCallback(function(msg)
    local body = msg.body
    if type(body) ~= "table" then return end
    if body.action == "clear" then
      clearAll()
    elseif body.action == "togglePause" then
      M.setPaused(not M.paused)
    elseif body.action == "history" then
      -- through the ui queue so it lands after any presses already in the page's pipeline
      ui(historyPage(tonumber(body.offset) or 0, tonumber(body.limit) or HISTORY_PAGE))
    elseif body.action == "clips" then
      ui(clipPage(tonumber(body.offset) or 0, tonumber(body.limit) or CLIP_PAGE))
    elseif body.action == "copyClip" then
      copyClip(tonumber(body.id) or 0)
    elseif body.action == "deleteClip" then
      db:exec("DELETE FROM clips WHERE id = " .. math.floor(tonumber(body.id) or 0))
      lastClip = nil  -- copying the same text again should save it again
      local offset, limit = tonumber(body.offset) or 0, tonumber(body.limit) or CLIP_PAGE
      local page = clipPage(offset, limit)
      -- deleted the last item on the last page: step back a page
      if #page.rows == 0 and page.offset > 0 then page = clipPage(page.offset - limit, limit) end
      ui(page)
    elseif body.action == "clearClips" then
      db:exec("DELETE FROM clips")
      lastClip = nil
      ui(clipPage(0, CLIP_PAGE))
    end
  end)
  M.wv = hs.webview.new(targetScreen():frame(), { developerExtrasEnabled = true }, uc)
    :windowStyle({ "borderless" })
    :behaviorAsLabels({ "canJoinAllSpaces" })
    :level(hs.drawing.windowLevels.normal)
    :shadow(false)
    :closeOnEscape(false)
    :deleteOnClose(false)
    :allowTextEntry(false)
    :navigationCallback(function(action)
      if action == "didFinishNavigation" then
        ready = true
        sendNow({ snapshot() })
        setStatus(currentStatus or "listening", true)
      end
    end)
  M.wv:url("file://" .. HTML_PATH)
  M.wv:show()
end

function M.toggleWindow()
  if not M.wv then return end
  if M.wv:isVisible() then M.wv:hide() else placeWindow(); M.wv:show() end
end

-- key capture -----------------------------------------------------------------

local heldMods = {}   -- code -> true for modifiers currently down
local soloMod = nil   -- modifier pressed alone; recorded on release if nothing joined it

local function record(label)
  local p = { t = nowMs(), label = label }
  buffer[#buffer + 1] = p
  ui({ type = "record", t = p.t, label = label })
end

local function onKey(e)
  local t = e:getType()

  if t == T.keyDown or t == T.keyUp then
    local kc = e:getKeyCode()
    if kc == FN_TAPPED then return end
    local code = CODES[kc]
    if t == T.keyUp then
      if code then ui({ type = "up", code = code }) end
      return
    end
    if code then ui({ type = "down", code = code }) end
    if e:getProperty(AUTOREPEAT) ~= 0 then return end
    soloMod = nil
    record(modPrefix(e:getFlags()) .. keyName(code, kc))

  elseif t == T.flagsChanged then
    local code = CODES[e:getKeyCode()]
    if code == "CapsLock" then  -- macOS sends one event per physical press, on and off
      ui({ type = "flash", code = code })
      record("Caps Lock")
      return
    end
    if code == "Fn" then  -- lit while held, recorded on press
      if e:getFlags().fn then
        ui({ type = "down", code = code })
        soloMod = nil
        record("Fn")
      else
        ui({ type = "up", code = code })
      end
      return
    end
    local cls = MOD_CLASS[code]
    if not cls then return end   -- anything unknown
    local flags = e:getFlags()
    if flags[cls] and not heldMods[code] then
      local othersHeld = next(heldMods) ~= nil
      heldMods[code] = true
      ui({ type = "down", code = code })
      if othersHeld then soloMod = nil else soloMod = code end
    else
      if flags[cls] then
        heldMods[code] = nil
        ui({ type = "up", code = code })
      else
        -- the class flag is gone, so both sides are up
        for c, _ in pairs(heldMods) do
          if MOD_CLASS[c] == cls then heldMods[c] = nil; ui({ type = "up", code = c }) end
        end
      end
      if soloMod == code then record(MOD_SYMBOL[cls] .. "+" .. NAMES[code]) end
      soloMod = nil
    end

  elseif t == T.systemDefined then
    local k = e:systemKey()
    local code = k and MEDIA[k.key]
    if not code then return end
    if k.down then
      ui({ type = "down", code = code })
      if not k["repeat"] then
        soloMod = nil
        record(modPrefix(e:getFlags()) .. code)
      end
    else
      ui({ type = "up", code = code })
    end
  end
end

-- lifecycle -------------------------------------------------------------------

M.paused = false

function M.setPaused(p)
  M.paused = p
  heldMods, soloMod = {}, nil
  setStatus(p and "paused" or "listening")
end

local function secureInputOn()
  local ok, on = pcall(hs.eventtap.isSecureInputEnabled)
  return ok and on
end

local function buildMenu()
  local visible = M.wv and M.wv:isVisible()
  return {
    { title = M.paused and "Resume recording" or "Pause recording", fn = function() M.setPaused(not M.paused) end },
    { title = visible and "Hide board" or "Show board", fn = M.toggleWindow },
    { title = "-" },
    { title = "Open data folder", fn = function() hs.execute('open "' .. MODULE_DIR .. '"') end },
    { title = "Reload Hammerspoon config", fn = hs.reload },
  }
end

function M.start()
  openDb()
  prune()

  M.tap = hs.eventtap.new({ T.keyDown, T.keyUp, T.flagsChanged, T.systemDefined }, function(e)
    if not M.paused then
      local ok, err = pcall(onKey, e)
      if not ok then print("keystroke_board: " .. tostring(err)) end
    end
    return false  -- never swallow the key
  end)
  if hs.accessibilityState() then M.tap:start() end

  createWindow()

  lastChangeCount = hs.pasteboard.changeCount()  -- don't record whatever was copied before startup
  M.clipTimer = hs.timer.doEvery(CLIP_POLL, pollClipboard)
  M.flushTimer = hs.timer.doEvery(2, flush)
  M.pruneTimer = hs.timer.doEvery(3600, prune)
  -- macOS disables an event tap that is ever slow to respond; turn it back on, and report secure input
  M.watchdog = hs.timer.doEvery(2, function()
    if not hs.accessibilityState() then setStatus("noaccess"); return end
    if not M.tap:isEnabled() then M.tap:start() end
    if M.paused then setStatus("paused")
    elseif secureInputOn() then setStatus("secure")
    else setStatus("listening") end
  end)

  M.screenWatcher = hs.screen.watcher.new(placeWindow):start()
  M.hotkey = hs.hotkey.bind(TOGGLE_HOTKEY[1], TOGGLE_HOTKEY[2], M.toggleWindow)
  M.menu = hs.menubar.new():setTitle("⌨"):setMenu(buildMenu)

  hs.shutdownCallback = function() flush() end
end

return M
